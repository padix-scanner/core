package reporter

import (
	"fmt"
	"io"

	"core/pkg/models"
)

// WriteMarkdown generates a markdown security assessment report.
func WriteMarkdown(w io.Writer, result models.ScanResult) error {
	if w == nil {
		return fmt.Errorf("report writer cannot be nil")
	}

	fmt.Fprintln(w, "# Padix Security Report")
	fmt.Fprintln(w)

	// Host information.
	fmt.Fprintln(w, "## Host Information")
	fmt.Fprintln(w)
	fmt.Fprintf(w, "| Field | Value |\n")
	fmt.Fprintf(w, "| --- | --- |\n")
	fmt.Fprintf(w, "| Hostname | %s |\n", valueOrNA(result.Host.Hostname))
	fmt.Fprintf(w, "| Operating OS | %s |\n", valueOrNA(result.Host.OS))
	fmt.Fprintf(w, "| OS Version | %s |\n", valueOrNA(result.Host.OSVersion))
	fmt.Fprintf(w, "| OS Confidence | %s |\n", valueOrNA(result.Host.OSConfidence))
	fmt.Fprintf(w, "| Kernel | %s |\n", valueOrNA(result.Host.Kernel))
	fmt.Fprintf(w, "| Architecture | %s |\n", valueOrNA(result.Host.Architecture))
	fmt.Fprintln(w)

	// Discovered services.
	fmt.Fprintln(w, "## Discovered Services")
	fmt.Fprintln(w)

	if len(result.Services) == 0 {
		fmt.Fprintln(w, "No services discovered.")
		fmt.Fprintln(w)
	} else {
		fmt.Fprintf(w, "| Port | Protocol | Service | State | Product |\n")
		fmt.Fprintf(w, "| --- | --- | --- | --- | --- |\n")
		for _, service := range result.Services {
			fmt.Fprintf(
				w,
				"| %d | %s | %s | %s | %s |\n",
				service.Port,
				service.Protocol,
				service.Name,
				service.State,
				valueOrNA(service.Product),
			)
		}
		fmt.Fprintln(w)
	}

	// Technologies.
	fmt.Fprintln(w, "## Technology Fingerprinting")
	fmt.Fprintln(w)

	technologyCount := 0

	for _, service := range result.Services {
		for _, tech := range service.Technologies {
			technologyCount++
			fmt.Fprintf(w, "### %s\n", tech.Name)
			fmt.Fprintf(w, "- **Version:** %s\n", valueOrNA(tech.Version))
			fmt.Fprintf(w, "- **Category:** %s\n", tech.Category)
			fmt.Fprintf(w, "- **Confidence:** %s\n", tech.Confidence)
			fmt.Fprintf(w, "- **Source:** %s\n", tech.Source)
			fmt.Fprintln(w)
		}
	}

	for _, tech := range result.Technologies {
		technologyCount++
		fmt.Fprintf(w, "### %s\n", tech.Name)
		fmt.Fprintf(w, "- **Version:** %s\n", valueOrNA(tech.Version))
		fmt.Fprintf(w, "- **Category:** %s\n", tech.Category)
		fmt.Fprintf(w, "- **Confidence:** %s\n", tech.Confidence)
		fmt.Fprintf(w, "- **Source:** %s\n", tech.Source)
		fmt.Fprintln(w)
	}

	if technologyCount == 0 {
		fmt.Fprintln(w, "No technologies identified.")
		fmt.Fprintln(w)
	}

	// Vulnerability findings.
	fmt.Fprintln(w, "## Vulnerability Assessment")
	fmt.Fprintln(w)

	mergedFindings := mergeExposedServices(result.Findings)
	if len(mergedFindings) == 0 {
		fmt.Fprintln(w, "No vulnerability findings available.")
		fmt.Fprintln(w)
	} else {
		for i, finding := range mergedFindings {
			fmt.Fprintf(w, "### %d. %s\n", i+1, finding.Title)
			fmt.Fprintf(w, "- **ID:** %s\n", finding.ID)
			fmt.Fprintf(w, "- **Category:** %s\n", displayFindingCategory(finding.Category))
			fmt.Fprintf(w, "- **Severity:** %s\n", finding.Severity)
			fmt.Fprintf(w, "- **Status:** %s\n", finding.Status)
			fmt.Fprintf(w, "- **Confidence:** %s\n", finding.Confidence)
			fmt.Fprintf(w, "- **Details:** %s\n", finding.Description)

			if finding.Evidence != "" {
				fmt.Fprintf(w, "- **Evidence:**\n\n%s\n\n", finding.Evidence)
			}
			fmt.Fprintln(w)
		}
	}

	// CVE findings.
	fmt.Fprintln(w, "## CVE Correlation")
	fmt.Fprintln(w)

	if len(result.CVEs) == 0 {
		fmt.Fprintln(w, "No CVE findings available.")
		fmt.Fprintln(w)
	} else {
		fmt.Fprintf(w, "| CVE | Package | Version | Severity | CVSS | Status |\n")
		fmt.Fprintf(w, "| --- | --- | --- | --- | --- | --- |\n")
		for _, cve := range result.CVEs {
			fmt.Fprintf(
				w,
				"| %s | %s | %s | %s | %.1f | %s |\n",
				cve.CVE,
				cve.Package,
				cve.Version,
				cve.Severity,
				cve.CVSS,
				cve.Status,
			)
		}
		fmt.Fprintln(w)
	}

	// Summary.
	fmt.Fprintln(w, "## Scan Summary")
	fmt.Fprintln(w)
	fmt.Fprintf(w, "- **Discovered services:** %d\n", len(result.Services))
	fmt.Fprintf(w, "- **Identified technologies:** %d\n", technologyCount)
	fmt.Fprintf(w, "- **Vulnerability findings:** %d\n", len(mergedFindings))
	fmt.Fprintf(w, "- **CVE findings:** %d\n", len(result.CVEs))
	fmt.Fprintln(w)
	fmt.Fprintf(w, "Generated by Padix Host Vulnerability Scanner\n")

	return nil
}
