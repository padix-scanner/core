package reporter

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"core/pkg/models"
)

func TestWriteMarkdown(t *testing.T) {
	var buf bytes.Buffer
	if err := WriteMarkdown(&buf, sampleResult()); err != nil {
		t.Fatal(err)
	}
	out := buf.String()

	for _, want := range []string{
		"# Padix Security Report",
		"## Host Information",
		"| Hostname | web01 |",
		"| Operating OS | Linux |",
		"## Discovered Services",
		"| Port | Protocol | Service | State | Product |",
		"| 80 | tcp | http | open | nginx |",
		"## Technology Fingerprinting",
		"### nginx",
		"## Vulnerability Assessment",
		"### 1. Exposed HTTP service",
		"## CVE Correlation",
		"| CVE | Package | Version | Severity | CVSS | Status |",
		"| CVE-2021-1234 | nginx | 1.18 | high | 7.5 | confirmed |",
		"## Scan Summary",
		"Generated by Padix Host Vulnerability Scanner",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("markdown output missing %q", want)
		}
	}
}

func TestWriteMarkdownMergesExposedServices(t *testing.T) {
	var buf bytes.Buffer
	if err := WriteMarkdown(&buf, sampleResult()); err != nil {
		t.Fatal(err)
	}
	out := buf.String()
	if got := strings.Count(out, "### 1. Exposed HTTP service"); got != 1 {
		t.Errorf("merged finding count = %d, want 1", got)
	}
	if strings.Contains(out, "### 2. Exposed HTTP service") {
		t.Error("duplicate exposed service finding not merged")
	}
}

func TestWriteMarkdownEmpty(t *testing.T) {
	var buf bytes.Buffer
	if err := WriteMarkdown(&buf, &models.ScanResult{}); err != nil {
		t.Fatal(err)
	}
	out := buf.String()
	for _, want := range []string{
		"No services discovered.",
		"No technologies identified.",
		"No vulnerability findings available.",
		"No CVE findings available.",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("empty markdown report missing %q", want)
		}
	}
}

func TestWriteMarkdownNilWriter(t *testing.T) {
	if err := WriteMarkdown(nil, &models.ScanResult{}); err == nil {
		t.Fatal("expected error for nil writer")
	}
}

func TestGenerateReportMarkdownToFile(t *testing.T) {
	path := filepath.Join(t.TempDir(), "report.md")
	if ok := GenerateReport(path, "markdown", sampleResult()); !ok {
		t.Fatal("GenerateReport returned false")
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if len(data) == 0 {
		t.Error("report file is empty")
	}
}
